  INSERT INTO products_fts(rowid, product_id, name_de, name_en, name_pt, brand)
  VALUES (new.rowid, new.id, new.name_de, new.name_en, new.name_pt, new.brand);
END;

CREATE TRIGGER IF NOT EXISTS products_ad AFTER DELETE ON products BEGIN
  INSERT INTO products_fts(products_fts, rowid, product_id, name_de, name_en, name_pt, brand)
  VALUES ('delete', old.rowid, old.id, old.name_de, old.name_en, old.name_pt, old.brand);
END;

